import { execFileSync, execSync } from 'node:child_process';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { homedir } from 'node:os';

async function licenses(directory, explicit) {
  const files = (await readdir(directory)).filter((name) =>
    /^(licen[cs]e|copying|notice)([._-].*)?$/i.test(name),
  );
  if (explicit && !files.includes(explicit)) files.push(explicit);
  const texts = [];
  for (const name of files) {
    try {
      const text = await readFile(join(directory, name), 'utf8');
      texts.push(`\n### ${name}\n\n\`\`\`\`text\n${text.trim()}\n\`\`\`\`\n`);
    } catch {
      /* Some packages have a LICENSE directory; use their SPDX expression below. */
    }
  }
  return (
    texts.join('') ||
    '\nNo standalone license file was supplied in this package; consult its upstream distribution and SPDX identifier above.\n'
  );
}

const paths = execSync('npm ls --omit=dev --all --parseable', {
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'pipe'],
})
  .trim()
  .split(/\r?\n/)
  .slice(1);
let npmText =
  '# Third-party npm notices\n\nGenerated by `npm run notices` from installed production dependencies. Upstream license text and copyright notices follow. The original application and demo assets are covered by LICENSE.\n';
const npmLicenses = new Map();
const upstreamLicense = {
  '@react-three/fiber': 'react-three-fiber.txt',
  '@mediapipe/tasks-vision': 'mediapipe.txt',
  draco3d: 'draco.txt',
  maath: 'maath.txt',
};
for (const path of [...new Set(paths)].sort()) {
  const pkg = JSON.parse(await readFile(join(path, 'package.json'), 'utf8'));
  const license =
    typeof pkg.license === 'object' ? pkg.license.type : (pkg.license ?? 'UNSPECIFIED');
  npmLicenses.set(pkg.name, license);
  npmText +=
    `\n## ${pkg.name} ${pkg.version}\n\nSPDX: ${pkg.name === 'webgl-constants' ? 'MIT (identified in the included LICENSE)' : license}\n` +
    (upstreamLicense[pkg.name]
      ? `\nLicense text supplied from the upstream project; see docs/licenses/sources.json.\n\n\`\`\`\`text\n${await readFile(`docs/licenses/${upstreamLicense[pkg.name]}`, 'utf8')}\n\`\`\`\`\n`
      : await licenses(path));
}
npmText +=
  '\n## Open CASCADE Technology (STEP runtime)\n\nThis software makes use of facilities provided by Open CASCADE Technology. The unmodified occt-import-js 0.0.23 runtime incorporates OCCT at commit d2abb6d844231cb8f29be6894440874a4700e4a5. See docs/cad-runtime.md for exact corresponding source and rebuild/replacement instructions.\n\n';
for (const name of ['OCCT-LGPL-2.1.txt', 'OCCT-LGPL-exception.txt'])
  npmText += `\n### ${name}\n\n\`\`\`\`text\n${await readFile(`docs/licenses/${name}`, 'utf8')}\n\`\`\`\`\n`;
await writeFile('THIRD_PARTY_NOTICES.md', npmText);

const cargo =
  process.env.CARGO ||
  join(homedir(), '.cargo', 'bin', process.platform === 'win32' ? 'cargo.exe' : 'cargo');
const metadata = JSON.parse(
  execFileSync(
    cargo,
    [
      'metadata',
      '--format-version',
      '1',
      '--locked',
      '--manifest-path',
      'src-tauri/Cargo.toml',
      '--filter-platform',
      'x86_64-pc-windows-msvc',
    ],
    { encoding: 'utf8', maxBuffer: 30 * 1024 * 1024 },
  ),
);
let rustText =
  '# Third-party Rust notices\n\nGenerated by `npm run notices` from the locked Cargo dependency graph for Windows x64. Includes runtime and build dependencies. Dual-licensed packages retain the upstream license alternatives. The application is covered by LICENSE.\n\nMPL-2.0 covered dependencies are unmodified. Their corresponding source is available from the exact crate source archive linked in each entry below; no proprietary source modifications are made by this application.\n';
const rustLicenses = new Set();
for (const pkg of metadata.packages
  .filter((pkg) => pkg.source)
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
  rustLicenses.add(pkg.license ?? 'SEE LICENSE FILE');
  rustText +=
    `\n## ${pkg.name} ${pkg.version}\n\nSPDX: ${pkg.license ?? 'SEE LICENSE FILE'}\n\nCorresponding source: https://crates.io/api/v1/crates/${pkg.name}/${pkg.version}/download\n` +
    (pkg.name === 'selectors'
      ? `\n\`\`\`\`text\n${await readFile('docs/licenses/MPL-2.0.txt', 'utf8')}\n\`\`\`\`\n`
      : await licenses(dirname(pkg.manifest_path), pkg.license_file));
}
await writeFile('THIRD_PARTY_RUST_NOTICES.md', rustText);
console.log(
  `npm production packages: ${npmLicenses.size}; license identifiers: ${[...new Set(npmLicenses.values())].join(', ')}`,
);
console.log(
  `Rust packages: ${metadata.packages.filter((pkg) => pkg.source).length}; license identifiers: ${[...rustLicenses].join(', ')}`,
);
